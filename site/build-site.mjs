// Builds the website's pages from their templates: every {{i:name}} becomes a
// Material Symbols icon - the app's own (frontend/src/lib/msym.js) plus the few
// only the site uses (msym-site.mjs) - inlined as SVG so the pages need no icon
// font or script.
//
//   node site/build-site.mjs
//
//   index.template.html       -> index.html        (the page)
//   wiki/index.template.html  -> wiki/index.html   (the wiki)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { MS } = await import(pathToFileURL(join(here, "..", "frontend", "src", "lib", "msym.js")).href);
const { MS_SITE } = await import(pathToFileURL(join(here, "msym-site.mjs")).href);
const ICONS = { ...MS, ...MS_SITE };

const PAGES = [["index.template.html", "index.html"], ["wiki/index.template.html", "wiki/index.html"]];

for (const [from, to] of PAGES) {
  const missing = new Set();
  const src = readFileSync(join(here, from), "utf8");
  const out = src.replace(/\{\{i:([a-z0-9_]+)\}\}/g, (_, name) => {
    const paths = ICONS[name];
    if (!paths) { missing.add(name); return ""; }
    return `<svg class="i" viewBox="0 -960 960 960" aria-hidden="true"><path d="${paths[0]}"/></svg>`;
  }).replace(
    "<!-- Generated by build-site.mjs (icons inlined). Edit the template. -->",
    "<!-- Generated by build-site.mjs from " + from.split("/").pop() + " - edit the template, not this file. -->");
  if (missing.size) {
    console.error(`${from}: no such icon in msym.js or msym-site.mjs:`, [...missing].join(", "));
    process.exit(1);
  }
  if (/[\u2013\u2014]/.test(out)) {            // house style: plain hyphens only
    console.error(`${from}: contains an en or em dash`);
    process.exit(1);
  }
  writeFileSync(join(here, to), out);
  console.log(`site/${to} written`);
}
